#!/usr/bin/env python
"""PO/POT reading and writing, and a GNU MO writer (ADR-0020).

Shared by ``extract_messages.py`` (source -> .pot) and
``compile_catalogs.py`` (.po -> .mo). No external tool and no dependency:
GNU gettext's ``xgettext``/``msgfmt`` are not installable as Python
dependencies and are absent on a stock Windows or macOS machine, so both
directions live in the repo.

Everything here is **deterministic**: entries are written in sorted msgid
order, source references sorted, and no timestamp goes into a header. That
is what lets CI regenerate a catalog and byte-compare it against the
committed one, which is the gate that stops the committed .mo from drifting
away from its .po.

Not supported, on purpose (ADR-0020): plural forms and message contexts.
German and English share the same plural rule, so ``ngettext`` would buy
almost nothing for a noticeable amount of machinery. A ``msgid_plural`` or
``msgctxt`` line in a .po file is therefore an error, not something quietly
mistranslated.

This module is loaded by path, never as ``packaging.pocatalog``: the repo's
``packaging/`` directory is not a Python package and the name collides with
the third-party ``packaging`` distribution.
"""

from __future__ import annotations

import re
import struct
from dataclasses import dataclass, field

MO_MAGIC = 0x950412DE  # little-endian GNU MO

#: Written verbatim as the header entry (msgid "") of a generated .pot. No
#: POT-Creation-Date: a timestamp would make the file differ on every run and
#: destroy the byte-compare gate.
POT_HEADER = (
    "Project-Id-Version: tta\n"
    "Report-Msgid-Bugs-To: https://github.com/olistroemer/Thesis_Text_Analyzer/issues\n"
    "MIME-Version: 1.0\n"
    "Content-Type: text/plain; charset=UTF-8\n"
    "Content-Transfer-Encoding: 8bit\n"
    "Language: \n"
)


class CatalogError(ValueError):
    """A .po/.pot file this reader refuses to guess about."""


@dataclass
class Entry:
    """One message: its msgid, its translation, and where it came from."""

    msgid: str
    msgstr: str = ""
    references: tuple[str, ...] = ()
    comments: tuple[str, ...] = ()  # translator comments, without the "# "


#: Leading comment block of a generated .pot.
POT_PREAMBLE = (
    "Translation template for the Thesis Text Analyzer (ADR-0020).",
    "Generated by packaging/extract_messages.py - do not edit by hand.",
    "Source msgids are English and ASCII (ADR-0018); translations live",
    "in tta/locale/<lang>/LC_MESSAGES/tta.po.",
)


@dataclass
class Catalog:
    """A .po/.pot file: the header entry plus the messages, msgid-keyed."""

    header: str = POT_HEADER
    entries: dict[str, Entry] = field(default_factory=dict)
    #: free comment lines above the header entry, without their "# " prefix
    preamble: tuple[str, ...] = ()

    def add(self, msgid: str, reference: str = "") -> Entry:
        entry = self.entries.get(msgid)
        if entry is None:
            entry = Entry(msgid)
            self.entries[msgid] = entry
        if reference and reference not in entry.references:
            entry.references = tuple(sorted(entry.references + (reference,)))
        return entry

    def sorted_entries(self) -> list[Entry]:
        """Messages in msgid order - the deterministic write order."""
        return [self.entries[msgid] for msgid in sorted(self.entries)]

    def untranslated(self) -> list[str]:
        """msgids with an empty msgstr, in msgid order."""
        return [e.msgid for e in self.sorted_entries() if not e.msgstr]


# -- PO escaping ---------------------------------------------------------------

_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\t": "\\t", "\r": "\\r"}
_UNESCAPES = {"\\": "\\", '"': '"', "n": "\n", "t": "\t", "r": "\r", "a": "\a", "b": "\b",
              "f": "\f", "v": "\v", "0": "\0"}


def escape(text: str) -> str:
    return "".join(_ESCAPES.get(char, char) for char in text)


def unescape(text: str) -> str:
    out: list[str] = []
    index = 0
    while index < len(text):
        char = text[index]
        if char == "\\" and index + 1 < len(text):
            nxt = text[index + 1]
            out.append(_UNESCAPES.get(nxt, nxt))
            index += 2
            continue
        out.append(char)
        index += 1
    return "".join(out)


def _quoted(prefix: str, text: str) -> list[str]:
    """A ``prefix "..."`` field, split after embedded newlines as msgfmt does.

    A single-line value stays on one line. A multi-line value is written as an
    empty first line followed by one line per segment, which is what every PO
    editor produces and expects.
    """
    if "\n" not in text:
        return ['%s "%s"' % (prefix, escape(text))]
    parts = text.split("\n")
    segments = [part + "\n" for part in parts[:-1]]
    if parts[-1]:
        segments.append(parts[-1])
    lines = ['%s ""' % prefix]
    lines += ['"%s"' % escape(segment) for segment in segments]
    return lines


# -- PO writing ----------------------------------------------------------------


def write_po(catalog: Catalog, *, template: bool) -> str:
    """Render a .pot (``template=True``) or a .po as text.

    A template writes every msgstr empty regardless of what the catalog
    holds; a .po writes the translations.
    """
    lines: list[str] = []
    preamble = POT_PREAMBLE if template else catalog.preamble
    lines += ["# %s" % line if line else "#" for line in preamble]
    lines += ['msgid ""']
    lines += _quoted("msgstr", catalog.header)
    for entry in catalog.sorted_entries():
        lines.append("")
        for comment in entry.comments:
            lines.append("#. %s" % comment)
        for reference in entry.references:
            lines.append("#: %s" % reference)
        lines += _quoted("msgid", entry.msgid)
        lines += _quoted("msgstr", "" if template else entry.msgstr)
    return "\n".join(lines) + "\n"


# -- PO reading ----------------------------------------------------------------

_STRING_LINE = re.compile(r'^\s*"(.*)"\s*$')
_FIELD_LINE = re.compile(r'^(msgid|msgstr|msgctxt|msgid_plural)\s+"(.*)"\s*$')


def read_po(text: str, *, origin: str = "<po>") -> Catalog:
    """Parse a .po/.pot into a Catalog.

    Deliberately strict: an unexpected line, a duplicate msgid, or a plural
    or context form raises instead of being silently dropped. This parser
    feeds the compiler, and a silently dropped message is a silently
    untranslated UI.
    """
    catalog = Catalog(header="")
    field_name: str | None = None
    values: dict[str, str] = {}
    references: list[str] = []
    comments: list[str] = []
    preamble: list[str] = []
    seen: set[str] = set()

    def flush(line_number: int) -> None:
        nonlocal field_name, values, references, comments
        if not values:
            field_name = None
            references, comments = [], []
            return
        if "msgid" not in values or "msgstr" not in values:
            raise CatalogError("%s:%d: entry without both msgid and msgstr" % (origin, line_number))
        msgid = values["msgid"]
        if msgid == "":
            catalog.header = values["msgstr"]
        else:
            if msgid in seen:
                raise CatalogError("%s:%d: duplicate msgid %r" % (origin, line_number, msgid))
            seen.add(msgid)
            catalog.entries[msgid] = Entry(
                msgid=msgid,
                msgstr=values["msgstr"],
                references=tuple(references),
                comments=tuple(comments),
            )
        field_name = None
        values = {}
        references, comments = [], []

    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.rstrip()
        if not line.strip():
            flush(number)
            continue
        if line.startswith("#"):
            if values:
                flush(number)
            if line.startswith("#:"):
                references.extend(line[2:].split())
            elif line.startswith("#."):
                comments.append(line[2:].strip())
            elif not seen and catalog.header == "":
                # Free comments above the header entry: the file's own
                # preamble. Exactly one space after the "#" is the separator
                # the writer adds, so exactly one is removed - anything more is
                # the author's own indentation and round-trips intact.
                body = line[1:]
                preamble.append(body[1:] if body.startswith(" ") else body)
            continue
        field_match = _FIELD_LINE.match(line)
        if field_match:
            name, value = field_match.group(1), field_match.group(2)
            if name in ("msgctxt", "msgid_plural"):
                raise CatalogError(
                    "%s:%d: %s is not supported (ADR-0020: no plural forms, no contexts)"
                    % (origin, number, name)
                )
            if name == "msgid" and "msgstr" in values:
                flush(number)
            field_name = name
            values[name] = unescape(value)
            continue
        string_match = _STRING_LINE.match(line)
        if string_match and field_name is not None:
            values[field_name] += unescape(string_match.group(1))
            continue
        raise CatalogError("%s:%d: cannot parse %r" % (origin, number, raw))
    flush(len(text.splitlines()) + 1)
    catalog.preamble = tuple(preamble)
    return catalog


# -- MO writing ----------------------------------------------------------------


def write_mo(catalog: Catalog, *, include_untranslated: bool = False) -> bytes:
    """Compile a Catalog to GNU MO bytes.

    Untranslated messages are omitted by default, which is what ``msgfmt``
    does: an empty msgstr in a .mo would translate the string to "" and blank
    the UI, whereas an absent key falls back to the msgid.

    The header entry (msgid "") is always written - ``gettext`` reads the
    charset from it. Keys are emitted in sorted order, so the output is a
    pure function of the input.
    """
    pairs: list[tuple[bytes, bytes]] = [(b"", catalog.header.encode("utf-8"))]
    for entry in catalog.sorted_entries():
        if not entry.msgstr and not include_untranslated:
            continue
        pairs.append((entry.msgid.encode("utf-8"), entry.msgstr.encode("utf-8")))
    pairs.sort(key=lambda item: item[0])

    count = len(pairs)
    # magic, revision, count, offset of key table, offset of value table,
    # hash-table size, hash-table offset. No hash table is written: the size
    # is 0 and Python's GNUTranslations builds its own dict.
    header_size = 7 * 4
    key_table = header_size
    value_table = key_table + count * 8
    offset = value_table + count * 8

    key_index: list[bytes] = []
    value_index: list[bytes] = []
    blob = bytearray()
    for key, _value in pairs:
        key_index.append(struct.pack("<II", len(key), offset + len(blob)))
        blob += key + b"\x00"
    for _key, value in pairs:
        value_index.append(struct.pack("<II", len(value), offset + len(blob)))
        blob += value + b"\x00"

    out = bytearray()
    # The last two fields are the hash-table size and offset. msgfmt writes
    # 0/0 when it emits no hash table, and CPython's GNUTranslations never
    # reads past the fifth field - it builds its own dict.
    out += struct.pack("<IIIIIII", MO_MAGIC, 0, count, key_table, value_table, 0, 0)
    out += b"".join(key_index)
    out += b"".join(value_index)
    out += blob
    return bytes(out)


# -- placeholder checking ------------------------------------------------------

_BRACE_FIELD = re.compile(r"\{([^{}]*)\}")


def format_fields(text: str) -> set[str]:
    """The ``{name}`` placeholders in a string, ignoring ``{{`` escapes."""
    return set(_BRACE_FIELD.findall(text.replace("{{", "").replace("}}", "")))


def placeholder_mismatches(catalog: Catalog) -> list[tuple[str, set[str], set[str]]]:
    """Entries whose msgstr placeholders differ from their msgid's.

    A dropped or renamed ``{path}`` is a ``KeyError`` at render time, in the
    locale nobody on the team reads first. Cheap to check, so it is checked.
    """
    bad = []
    for entry in catalog.sorted_entries():
        if not entry.msgstr:
            continue
        wanted = format_fields(entry.msgid)
        got = format_fields(entry.msgstr)
        if wanted != got:
            bad.append((entry.msgid, wanted, got))
    return bad
